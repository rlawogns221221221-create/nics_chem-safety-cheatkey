rng = np.random.default_rng(20261121)

BPM = 120
박 = 60 / BPM            # 0.5초
길이 = 30.0
N = int(SR * (길이 + 1.0))
L = np.zeros(N)
R = np.zeros(N)

# 무대와 같은 시각
T = [4.0, 10.0, 16.0, 22.0]          # 도구 제목 · 큰 북
끝북 = 28.0
켜짐 = [2.0, 2.25, 2.5, 2.75]         # 처음 카드가 하나씩 켜짐
다켜짐 = [27.0, 27.25, 27.5, 27.75]    # 끝에서 넷이 다시 켜짐


def 들(k):
    return T[k] - 0.5        # 카드로 들어가기 시작


def 나(k):
    return T[k] + 4.25       # 카드에서 나오기 시작


def hz(m):
    return 440.0 * 2 ** ((m - 69) / 12)


def 넣기(t0, sig, gain=1.0, pan=0.0):
    """t0 초 자리에 소리를 얹음 — pan 은 -1(왼쪽) ~ 1(오른쪽)"""
    i = int(round(t0 * SR))
    if i >= N:
        return
    sig = sig[: N - i] * gain
    L[i: i + len(sig)] += sig * np.sqrt((1 - pan) / 2) * 1.414
    R[i: i + len(sig)] += sig * np.sqrt((1 + pan) / 2) * 1.414


def 시간(d):
    return np.arange(int(d * SR)) / SR


def 톱니(f, d, 배음=10, 기울기=1.2):
    """배음을 직접 더한 톱니파 — 높은 배음을 줄여 거칠지 않게(필터 없이)"""
    t = 시간(d)
    s = np.zeros_like(t)
    for k in range(1, 배음 + 1):
        if f * k > SR / 2.2:
            break
        s += np.sin(2 * np.pi * f * k * t) / k ** 기울기
    return s


def 낮춤(x, n):
    """이동평균 — 소음을 둥글게(저역만 남김)"""
    return np.convolve(x, np.ones(n) / n, mode="same")


def 킥(d=0.34, f0=110, f1=44):
    t = 시간(d)
    f = f1 + (f0 - f1) * np.exp(-t / 0.05)
    ph = 2 * np.pi * np.cumsum(f) / SR
    return np.sin(ph) * np.exp(-t / 0.12) + 0.12 * rng.standard_normal(len(t)) * np.exp(-t / 0.004)


def 부드러운북(d=2.0):
    """장면이 바뀌는 자리의 강조음 — 부드러운 북(2026-11-22 사용자 — 폭발음·총소리 같다).
    '딱' 하고 터지는 첫소리를 만들던 것(밝은 소음 터짐 · 순간에 솟는 들머리)을 뺐습니다.
    낮은 음(68 → 42Hz)이 0.04초에 걸쳐 둥글게 차오른 뒤 천천히 잦아들고, 소음은 두 번
    둥글게 깎아(약 500Hz 아래) 숨소리처럼만 얹습니다 — 무게는 남고 터지는 맛은 없습니다."""
    t = 시간(d)
    f = 42 + 26 * np.exp(-t / 0.18)
    ph = 2 * np.pi * np.cumsum(f) / SR
    오름 = 0.5 - 0.5 * np.cos(np.pi * np.minimum(1, t / 0.04))
    몸 = (np.sin(ph) + 0.22 * np.sin(2 * ph)) * 오름 * np.exp(-t / 0.75)
    숨 = 낮춤(낮춤(rng.standard_normal(len(t)), 90), 90) * 오름 * np.exp(-t / 0.3) * 7.0
    return 몸 * 1.15 + 숨


def 둥근탐(f0=120, d=0.45):
    """잡음 없는 둥근 탐 — 원래 탐의 '탁' 하는 잡음 첫소리를 빼고 들머리를 8ms 로 둥글게"""
    t = 시간(d)
    f = f0 * (0.6 + 0.4 * np.exp(-t / 0.07))
    ph = 2 * np.pi * np.cumsum(f) / SR
    오름 = 0.5 - 0.5 * np.cos(np.pi * np.minimum(1, t / 0.008))
    return np.sin(ph) * 오름 * np.exp(-t / 0.14)


def 붐(d=1.8):
    """(예전 강조음 — 첫 판의 큰 북. 이 판에서는 쓰지 않음. 남겨 둔 것은 첫 판과 견줘 보려는 것)"""
    t = 시간(d)
    f = 34 + 60 * np.exp(-t / 0.08)
    ph = 2 * np.pi * np.cumsum(f) / SR
    낮은 = np.sin(ph) * np.exp(-t / 0.55)
    소음 = 낮춤(rng.standard_normal(len(t)), 18) * np.exp(-t / 0.25) * 2.2
    return 낮은 * 1.1 + 소음


def 탐(f0=150, d=0.4):
    t = 시간(d)
    f = f0 * (0.55 + 0.45 * np.exp(-t / 0.06))
    ph = 2 * np.pi * np.cumsum(f) / SR
    return np.sin(ph) * np.exp(-t / 0.13) + 0.25 * 낮춤(rng.standard_normal(len(t)), 4) * np.exp(-t / 0.02)


def 무거운탐(d=0.5):
    """마디 셋째 박의 무거운 한 방 — 스네어 대신 낮은 탐 + 둥근 소음"""
    t = 시간(d)
    # 잡음은 둥글게 깎아(약 1.5kHz 아래) 둠 — 밝게 두면 스네어처럼 '딱' 하고 터졌습니다(2026-11-22)
    return 탐(118, d) + 0.55 * 낮춤(rng.standard_normal(len(t)), 30) * np.exp(-t / 0.07) * 1.6


def 뜯기(m, d=0.24, 밝기=7):
    """8분음 반복음 한 개 — 짧게 뜯는 낮은 소리"""
    t = 시간(d)
    return 톱니(hz(m), d, 배음=밝기) * np.exp(-t / 0.07) * np.minimum(1, t / 0.003)


def 패드(음들, d, 붙임=0.3, 배음=7, 떨빠르기=2.0, 떨깊이=0.07):
    t = 시간(d)
    s = np.zeros_like(t)
    for m in 음들:
        for 어긋 in (-0.1, 0.0, 0.11):           # 세 줄을 살짝 어긋나게 — 현악기처럼 두껍게
            s += 톱니(hz(m + 어긋), d, 배음=배음, 기울기=1.7)
    env = np.minimum(1, t / 붙임) * np.minimum(1, (d - t) / 0.25)
    떨림 = 1 + 떨깊이 * np.sin(2 * np.pi * 떨빠르기 * t)   # 느리고 얕은 떨림
    return s * env * 떨림 / (len(음들) * 3)


def 한방(음들, d=1.3):
    """제목이 뜰 때의 금관 같은 한 방 — 빨리 부풀었다가 낮게 남음(높은 배음은 줄임)"""
    t = 시간(d)
    s = np.zeros_like(t)
    for m in 음들:
        for 어긋 in (-0.06, 0.07):
            s += 톱니(hz(m + 어긋), d, 배음=9, 기울기=1.5)
    # 첫소리를 0.07초에 걸쳐 엶 — 0.025초였을 때는 큰 북과 겹쳐 '딱' 소리를 보탰습니다
    env = (0.5 - 0.5 * np.cos(np.pi * np.minimum(1, t / 0.07))) * (0.35 + 0.65 * np.exp(-t / 0.3)) \
        * np.minimum(1, (d - t) / 0.3)
    return s * env / (len(음들) * 2)


def 종(m, d=1.0):
    """카드가 켜지거나 짚일 때의 낮은 종소리 — 사인 + 어긋난 배음 하나를 짧게"""
    t = 시간(d)
    f = hz(m)
    s = (np.sin(2 * np.pi * f * t) * np.exp(-t / 0.38)
         + 0.35 * np.sin(2 * np.pi * 2 * f * t) * np.exp(-t / 0.16)
         + 0.12 * np.sin(2 * np.pi * 2.76 * f * t) * np.exp(-t / 0.07))
    return s * np.minimum(1, t / 0.004)


def 톡(d=0.14):
    """누를 때의 짧은 '톡' — 높은 딸깍 대신 둥근 낮은 소리"""
    t = 시간(d)
    return 탐(230, d) * 0.8 + 0.3 * 낮춤(rng.standard_normal(len(t)), 5) * np.exp(-t / 0.01)


def 바람(d, 오름=True):
    """카메라가 들어갈 때 차오르는(오름) · 나올 때 내려앉는 낮은 바람 소리.
    어두운 소음과 밝은 소음을 시간에 따라 섞어 음색이 열리거나 닫히게 함(필터 없이)"""
    t = 시간(d)
    x = t / d
    어둠 = 낮춤(rng.standard_normal(len(t)), 40) * 3.2
    밝음 = 낮춤(rng.standard_normal(len(t)), 7) * 1.3
    섞 = x if 오름 else 1 - x
    소음 = 어둠 * (1 - 섞) + 밝음 * 섞
    f = 90 * (5.0 ** x) if 오름 else 450 * (0.2 ** x)
    ph = 2 * np.pi * np.cumsum(f) / SR
    음 = np.sin(ph) * 0.45
    env = x ** 2.2 if 오름 else np.minimum(1, t / 0.04) * np.exp(-t / (d * 0.35))
    return (소음 + 음) * env


# ── 화성 — 도구 01 Em · 02 C · 03 D · 04 B(장화음, 끌어 두기) · 끝 Em ─────────────
뿌리 = [40, 36, 38, 35]                         # 반복음 뿌리 E2 · C2 · D2 · B1
화음 = [[47, 52, 55, 59], [48, 52, 55, 60], [45, 50, 54, 57], [47, 51, 54, 59]]   # 가운데 음역
한방음 = [[52, 59, 64], [48, 55, 60], [50, 57, 62], [47, 54, 59]]
끝화음 = [40, 47, 52, 55, 59]

# ── 0 ~ 4초 : 여는 장면 — 큰 북 한 번 · 낮은 울림 · 카드가 켜질 때마다 종 ────────────
넣기(0.0, 부드러운북(1.8), 0.62)
넣기(0.0, 패드([40, 47, 52], 4.0, 붙임=1.6, 떨빠르기=1.5), 0.24)       # Em 낮은 화음이 천천히 차오름
넣기(0.0, 톱니(hz(28), 4.0, 배음=5, 기울기=1.8) * np.minimum(1, 시간(4.0) / 1.5), 0.18)   # 낮은 베이스
for t0 in (1.0, 1.25):                          # 심장 박동 한 번
    넣기(t0, 킥(0.28, 90, 40), 0.5 if t0 == 1.0 else 0.34)
넣기(1.4, 바람(0.6, True), 0.10)                # 휴대전화가 올라옴
for i, t0 in enumerate(켜짐):                   # 카드 넷이 켜짐 — Em 화음을 낮은 데서부터
    넣기(t0, 종([52, 55, 59, 64][i]), 0.30, pan=(-0.25, -0.08, 0.08, 0.25)[i])
for t0 in (2.0, 3.0):
    넣기(t0, 킥(), 0.45)

# ── 반복음 — 2초부터 28초까지 8분음 · 3-3-2 강세 · 여덟째 칸만 반음 위 ────────────────
강세 = {0, 3, 6}
for 칸 in range(4, 56):                          # 2.0초 ~ 27.75초
    b = 칸 / 2                                   # 박
    t0 = b * 박
    k = max([i for i in range(4) if T[i] - 0.001 <= t0] or [0])
    r = 뿌리[k]
    j = 칸 % 8
    m = r + 1 if j == 7 else r
    센 = j in 강세
    g = 0.25 if 센 else 0.14
    if t0 < 4.0:
        g *= 0.35 + 0.65 * (t0 - 2.0) / 2.0      # 여는 장면에서는 점점 커짐
    넣기(t0, 뜯기(m, 밝기=8 if 센 else 6), g, pan=-0.15 if 칸 % 2 else 0.15)

# ── 도구 넷 ───────────────────────────────────────────────────────────
for k in range(4):
    t0 = T[k]
    마지막 = k == 3
    구간 = (끝북 if 마지막 else T[k] + 6.0) - t0
    # 큰 북 + 금관 한 방 + 낮은 탐
    넣기(t0, 부드러운북(), 0.95 if k in (0, 3) else 0.85)
    넣기(t0, 둥근탐(110), 0.35)
    넣기(t0, 한방(한방음[k]), 0.34)
    # 화음 · 베이스 — 다음 큰 북까지 이어짐
    넣기(t0, 패드(화음[k], 구간, 붙임=0.12), 0.27)
    넣기(t0, 톱니(hz(뿌리[k] - 12), 구간, 배음=5, 기울기=1.8)
        * np.minimum(1, (구간 - 시간(구간)) / 0.1), 0.22)
    # 시연 동안(0 ~ 4초) 북 — 8분음 0·3·6 칸에 킥(반복음 강세와 같은 자리), 4 칸에 무거운 탐.
    # 첫 칸은 큰 북과 겹치므로 킥을 빼고, 4초 뒤(나오기·첫 화면)에는 북을 쉼
    for 칸 in range(0, 16):                      # 4초 = 8분음 16칸
        tt = t0 + 칸 * 0.25
        j = 칸 % 8
        if j in (0, 3, 6) and 칸 > 0:
            넣기(tt, 킥(), 0.6 if j == 0 else 0.48)
        if j == 4:
            넣기(tt, 무거운탐(), 0.36, pan=0.1)
    # 카드에서 나옴 — 바람이 내려앉고, 첫 화면에 닿는 순간 낮은 쿵 + '했음' 종
    넣기(나(k), 바람(0.55, False), 0.16)
    넣기(나(k) + 0.5, 둥근탐(75, 0.4), 0.42)
    넣기(나(k) + 0.5, 종(뿌리[k] + 12, 0.8), 0.24)
    if 마지막:
        continue
    # 다음 카드를 짚음(다음 화성의 뿌리음으로 미리) · 누름 · 들어가기
