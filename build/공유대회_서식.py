def 확인(경로):
    """만든 파일이 열리는지 확인합니다 — 압축·XML 이 성하고, 자리표시 글자가
    남지 않았고, 들어갔어야 할 수치가 실제로 들어갔는지."""
    import xml.etree.ElementTree as ET
    with zipfile.ZipFile(경로) as z:
        나쁜 = z.testzip()
        if 나쁜:
            raise SystemExit("압축이 깨졌습니다: " + 나쁜)
        xml = z.read("Contents/section0.xml").decode("utf-8")
    try:
        ET.fromstring(xml)          # 한글이 열기 전에 여기서 걸러집니다
    except ET.ParseError as e:
        raise SystemExit("XML 이 깨졌습니다: %s" % e)
    남은 = [w for w in ("휴먼명조", "중고딕 13pt", "HY헤드라인M",
                      "ㅇㅇ과", "ㅇㅇㅇ 사(주)무관")
           if w in xml]
    print("문단 %d개" % len(문단들(xml)))
    if 남은:
        print("⚠ 자리표시 글자가 남았습니다:", ", ".join(남은))
    else:
        print("자리표시 글자 없음 ✔")
    for w in (기관, "1,849", "1,947", "7,491", "46분"):
        if w not in xml:
            print("⚠ 들어갔어야 할 글이 없습니다:", w)


def 글로(경로):
    """한글 파일과 **같은 내용**을 읽기 쉬운 글로 뽑습니다.

    두 벌을 손으로 따로 쓰면 반드시 어긋납니다. 그래서 문서도 이 파일에서
    뽑습니다 — 내용을 고칠 곳은 위쪽 목록 한 곳뿐입니다.
    """
    머리 = {"o": "○ ", "-": "  - ", "*": "   * "}

    def 뭉치(제목, 줄들):
        yield "### %s" % 제목
        yield ""
        for 표, 글 in 줄들:
            yield 머리[표] + 글
        yield ""

    줄 = ["# [붙임2] (혁신부문) 기관별 대표사례 — 작성본",
         "",
         "> `build/공유대회_서식.py` 가 한글 파일과 함께 만든 것입니다.",
         "> 내용을 고치려면 그 파일 위쪽의 목록을 고치고 다시 돌리세요.",
         "",
         "- 분야 : **① 서비스혁신**",
         "- 사례명 : **%s**" % 사례명,
         "- 기관 : %s" % 기관,
         "",
         "---",
         "",
         "## 【서식1】 사전심사 요약본 (1장)",
         ""]
    줄 += list(뭉치("추진배경(또는 목적)", 요약배경))
    줄 += list(뭉치("주요내용", 요약내용))
    줄 += list(뭉치("주요성과(또는 기대효과)", 요약성과))
    줄 += ["### 추진 이전(AS-IS) → 추진 이후(TO-BE)", "",
          "| 추진 이전(AS-IS) | 추진 이후(TO-BE) |", "|---|---|"]
    줄 += ["| • %s | • %s |" % (a, b) for a, b in 대비]
    줄 += ["", "### 성과 유형", "", "**☑ 서비스혁신** · □ 기관 협업 · □ 공공성 강화",
          "", "---", "", "## 【서식2】 우수사례 (3장 이내)", "",
          "### %s (%s)" % (사례명, 기관), "",
          "| | |", "|---|---|",
          "| 성과 유형 | **☑ 서비스혁신** □ 기관 협업 □ 공공성 강화 |",
          "| 부서명 | %s |" % 부서,
          "| 과제담당자 | %s · %s · %s |" % (담당, 전화, 메일 or "(이메일)"),
          "| 사례중복 확인 | 타 행사 수상 □ 있음 / **☑ 없음** |", ""]
    for 제목, 줄들 in (("추진배경(또는 목적)", 배경),
                    ("추진 내용(추진 경과)", 내용),
                    ("장애요인 및 극복방법(또는 성공요인)", 장애),
                    ("주요성과(또는 기대 효과)", 성과)):
        줄 += list(뭉치(제목, 줄들))
    줄 += ["| 추진 이전(AS-IS) | 추진 이후(TO-BE) |", "|---|---|"]
    줄 += ["| • %s | • %s |" % (a, b) for a, b in 대비_짧게]
    줄 += [""]
    줄 += list(뭉치("향후 계획", 계획))
    줄 += ["---", "", "## 【서식3】 요약본 (1행)", "",
          "| 연번 | 기관명 / 부서 / 담당자 / 전화 | 주요내용 |", "|---|---|---|",
          "| 1 | %s<br>%s<br>%s<br>%s | **%s**<br>%s<br>* %s |"
          % (기관, 부서, 담당, 전화, 요약3제목,
             "<br>".join("•(%s) %s" % (t, g) for t, g in 요약3), 요약3꼬리),
          ""]
    with open(경로, "w", encoding="utf-8") as f:
        f.write("\n".join(줄) + "\n")
    return 경로


