def 감싸기(s):
    """XML 에 그대로 넣을 수 있게 특수문자를 바꿉니다."""
    return (s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


def 문단들(xml):
    """section0.xml 을 문단 단위로 잘라 [(시작, 끝, 원문)] 로 돌려줍니다.

    ⚠ 정규식 하나로 `<hp:p …>…</hp:p>` 를 잡으면 안 됩니다. 표(hp:tbl)가
    문단 **안에** 들어 있어서 문단이 서로 겹치기 때문입니다 — 짧게 잡으면
    바깥 문단의 여는 태그와 표 안 문단의 닫는 태그가 짝지어져 XML 이
    깨집니다(실제로 한 번 깨뜨렸습니다). 여는·닫는 태그를 세어 짝을 맞춥니다.
    """
    tok = re.compile(r"<hp:p\b[^>]*?(/?)>|</hp:p>")
    스택, 결과 = [], []
    for m in tok.finditer(xml):
        if m.group(0).startswith("</"):
            결과.append((스택.pop(), m.end()))
        elif m.group(1) == "/":          # <hp:p …/> 처럼 혼자 닫는 것
            결과.append((m.start(), m.end()))
        else:
            스택.append(m.start())
    if 스택:
        raise SystemExit("문단 태그의 짝이 맞지 않습니다")
    결과.sort()
    return [(a, b, xml[a:b]) for a, b in 결과]


def 새문단(틀, 조각):
    """틀 문단을 복제하고 글자만 갈아 끼웁니다.

    틀의 paraPrIDRef(문단모양)와 hp:run 의 charPrIDRef(글자모양)를 그대로
    쓰기 때문에 글꼴·크기·들여쓰기가 원본과 같아집니다.
    조각 = [(charPrIDRef, 글), ...]
    """
    머리 = re.match(r"<hp:p\b[^>]*>", 틀).group(0)
    꼬리 = re.search(r"<hp:linesegarray>.*?</hp:linesegarray>", 틀, re.S)
    꼬리 = 꼬리.group(0) if 꼬리 else ""
    runs = "".join(
        '<hp:run charPrIDRef="%s"><hp:t>%s</hp:t></hp:run>' % (c, 감싸기(t))
        for c, t in 조각)
    return 머리 + runs + 꼬리 + "</hp:p>"


def 개조식(틀들, 줄들):
    """('o'|'-'|'*', 글) 목록을 문단 XML 목록으로 바꿉니다.

    틀들 = {'o': (틀문단, 머리charPr, 글자charPr), '-': …, '*': …}
    머리는 원본이 쓰는 들여쓰기 공백을 그대로 씁니다.
    """
    머리글 = {"o": " ○ ", "-": "   - ", "*": "    * "}
    나온것 = []
    for 표, 글 in 줄들:
        틀, c머리, c글 = 틀들[표]
        나온것.append(새문단(틀, [(c머리, 머리글[표]), (c글, 글)]))
    return 나온것


