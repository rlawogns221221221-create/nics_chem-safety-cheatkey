끝화음 = [40, 47, 52, 55, 59]
마디4 = 8.0


def 화음칸(t):
    return int(max(0.0, t - 화음원점) // 마디4) % 4


# ── 처음 — 가상 사고가 뜨는 장면(박자 없음 → 심장 박동) ─────────────────────────
