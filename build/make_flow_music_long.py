import json
import pathlib
import sys
import wave

import numpy as np

SR = 44100
OUT = pathlib.Path(sys.argv[1])
판 = json.loads(sys.argv[2])
rng = np.random.default_rng(20261123)

BPM = 120
박 = 60 / BPM
길이 = float(판["길이"])
N = int(SR * (길이 + 1.0))
L = np.zeros(N)
R = np.zeros(N)


def hz(m):
    return 440.0 * 2 ** ((m - 69) / 12)


def 넣기(t0, sig, gain=1.0, pan=0.0):
    """t0 초 자리에 소리를 얹음 — pan 은 -1(왼쪽) ~ 1(오른쪽)"""
    i = int(round(t0 * SR))
    if i >= N or i < 0:
        return
    sig = sig[: N - i] * gain
    L[i: i + len(sig)] += sig * np.sqrt((1 - pan) / 2) * 1.414
    R[i: i + len(sig)] += sig * np.sqrt((1 + pan) / 2) * 1.414


def 시간(d):
    return np.arange(int(d * SR)) / SR


def 톱니(f, d, 배음=10, 기울기=1.2):
    """배음을 직접 더한 톱니파 — 높은 배음을 줄여 거칠지 않게(필터 없이)"""
    t = 시간(d)
    s = np.zeros_like(t)
    for k in range(1, 배음 + 1):
        if f * k > SR / 2.2:
            break
        s += np.sin(2 * np.pi * f * k * t) / k ** 기울기
    return s


def 낮춤(x, n):
    """이동평균 — 소음을 둥글게(저역만 남김)"""
    return np.convolve(x, np.ones(n) / n, mode="same")


def 킥(d=0.34, f0=110, f1=44):
    t = 시간(d)
    f = f1 + (f0 - f1) * np.exp(-t / 0.05)
    ph = 2 * np.pi * np.cumsum(f) / SR
    오름 = 0.5 - 0.5 * np.cos(np.pi * np.minimum(1, t / 0.004))
    return np.sin(ph) * np.exp(-t / 0.12) * 오름


def 부드러운북(d=2.0):
    """장면이 바뀌는 자리의 강조음 — 줌인 판과 같은 부드러운 북.
    낮은 음(68 → 42Hz)이 0.04초에 걸쳐 둥글게 차오른 뒤 천천히 잦아들고, 소음은 두 번 둥글게 깎아
    (약 500Hz 아래) 숨소리처럼만 얹습니다 — 무게는 남고 터지는 맛은 없습니다."""
    t = 시간(d)
    f = 42 + 26 * np.exp(-t / 0.18)
    ph = 2 * np.pi * np.cumsum(f) / SR
    오름 = 0.5 - 0.5 * np.cos(np.pi * np.minimum(1, t / 0.04))
    몸 = (np.sin(ph) + 0.22 * np.sin(2 * ph)) * 오름 * np.exp(-t / 0.75)
    숨 = 낮춤(낮춤(rng.standard_normal(len(t)), 90), 90) * 오름 * np.exp(-t / 0.3) * 7.0
    return 몸 * 1.15 + 숨


def 둥근탐(f0=120, d=0.45):
    """잡음 없는 둥근 탐 — 들머리를 8ms 로 둥글게"""
    t = 시간(d)
    f = f0 * (0.6 + 0.4 * np.exp(-t / 0.07))
    ph = 2 * np.pi * np.cumsum(f) / SR
    오름 = 0.5 - 0.5 * np.cos(np.pi * np.minimum(1, t / 0.008))
    return np.sin(ph) * 오름 * np.exp(-t / 0.14)


def 무거운탐(d=0.5):
    """마디 셋째 박의 무거운 한 방 — 둥근 탐 + 아주 둥근 소음(스네어처럼 '딱' 하지 않게)"""
    t = 시간(d)
    return 둥근탐(118, d) + 0.55 * 낮춤(rng.standard_normal(len(t)), 30) * np.exp(-t / 0.07) * 1.6


def 뜯기(m, d=0.24, 밝기=7):
    """8분음 반복음 한 개 — 짧게 뜯는 낮은 소리"""
    t = 시간(d)
    return 톱니(hz(m), d, 배음=밝기) * np.exp(-t / 0.07) * np.minimum(1, t / 0.003)


def 패드(음들, d, 붙임=0.3, 배음=7, 떨빠르기=2.0, 떨깊이=0.07, 놓임=0.25):
    t = 시간(d)
    s = np.zeros_like(t)
    for m in 음들:
        for 어긋 in (-0.1, 0.0, 0.11):           # 세 줄을 살짝 어긋나게 — 현악기처럼 두껍게
            s += 톱니(hz(m + 어긋), d, 배음=배음, 기울기=1.7)
    env = np.minimum(1, t / 붙임) * np.minimum(1, (d - t) / 놓임)
    떨림 = 1 + 떨깊이 * np.sin(2 * np.pi * 떨빠르기 * t)
    return s * env * 떨림 / (len(음들) * 3)


def 한방(음들, d=1.3):
    """금관 같은 한 방 — 첫소리를 0.07초에 걸쳐 엶(큰 북과 겹쳐 '딱' 소리를 보태지 않게)"""
    t = 시간(d)
    s = np.zeros_like(t)
    for m in 음들:
        for 어긋 in (-0.06, 0.07):
            s += 톱니(hz(m + 어긋), d, 배음=9, 기울기=1.5)
    env = (0.5 - 0.5 * np.cos(np.pi * np.minimum(1, t / 0.07))) * (0.35 + 0.65 * np.exp(-t / 0.3)) \
        * np.minimum(1, (d - t) / 0.3)
    return s * env / (len(음들) * 2)


def 종(m, d=1.2):
    """낮은 종소리 — 사인 + 어긋난 배음 하나를 짧게"""
    t = 시간(d)
    f = hz(m)
    s = (np.sin(2 * np.pi * f * t) * np.exp(-t / 0.45)
         + 0.35 * np.sin(2 * np.pi * 2 * f * t) * np.exp(-t / 0.18)
         + 0.12 * np.sin(2 * np.pi * 2.76 * f * t) * np.exp(-t / 0.07))
    return s * (0.5 - 0.5 * np.cos(np.pi * np.minimum(1, t / 0.006)))


def 바람(d, 오름=True):
    """다음 장면으로 넘어갈 때 차오르는 낮은 바람 소리(필터 없이 — 어두운·밝은 소음을 섞음)"""
    t = 시간(d)
    x = t / d
    어둠 = 낮춤(rng.standard_normal(len(t)), 40) * 3.2
    밝음 = 낮춤(rng.standard_normal(len(t)), 12) * 1.1
    섞 = x if 오름 else 1 - x
    소음 = 어둠 * (1 - 섞) + 밝음 * 섞
    f = 90 * (5.0 ** x) if 오름 else 450 * (0.2 ** x)
    ph = 2 * np.pi * np.cumsum(f) / SR
    env = x ** 2.2 if 오름 else np.minimum(1, t / 0.04) * np.exp(-t / (d * 0.35))
    return (소음 + np.sin(ph) * 0.45) * env


def 반박(t):
    return round(t / 박) * 박


시작 = float(판.get("시작", 0.0))                # 이 앞은 조용(첫 장)
사고 = float(판.get("사고", 1.0))
