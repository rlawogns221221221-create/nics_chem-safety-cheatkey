def 업체합치기(목록):
    """같은 업체가 표 여러 곳에 있으면 하나로 합칩니다.

    ⚠ 표 13(대구청 251)은 표 14(전국취합) 안의 대구청 101건과 겹칩니다.
      그냥 둘을 다 넣으면 목록에 같은 업체가 두 줄로 나옵니다.
      **처리가능 폐기물은 표 13·03 에만 있으므로** 합칠 때 그 칸을
      살려 옮깁니다 — 분류안이 필수라고 못 박은 항목입니다.
    """
    def 열쇠(x):
        이름 = re.sub(r"[\s()（）㈜\(주\)주식회사]", "", x["업체명"])
        # ⚠ **갈래를 열쇠에 넣습니다.** 한 업체가 허가를 여럿 가진 경우가
        #   많습니다((주)엔아이티는 수집·운반 / 중간처분(소각) /
        #   중간처분(중화) / 종합재활용 넷). 업체 이름만으로 합치면 그중
        #   한 갈래만 남아, "폐산을 중화할 곳"을 찾는 사람에게 그 업체가
        #   보이지 않습니다. 갈래마다 한 줄로 둡니다.
        return (이름, x["시도"], x["갈래"])

    묶음 = {}
    차례 = []
    for x in 목록:
        k = 열쇠(x)
        if k not in 묶음:
            묶음[k] = dict(x)
            묶음[k]["_출처들"] = [x["자료출처"]]
            차례.append(k)
            continue
        a = 묶음[k]
        a["_출처들"].append(x["자료출처"])
        # 빈칸만 채웁니다 — 먼저 들어온 값을 덮지 않습니다
        for 칸 in ("주소", "대표전화", "시군구", "처리가능폐기물", "보유장비",
                  "협의권역", "확인못함"):
            if not a[칸] and x[칸]:
                a[칸] = x[칸]
        # 찾을 권역은 덮지 않고 **합칩니다** — 표마다 아는 권역이 다릅니다
        a["찾을권역"] = 찾을권역만들기(a.get("찾을권역", ""),
                                x.get("찾을권역", ""))
        # 허가 현황은 두 자료의 표기를 모두 보여 줍니다(허가가 여러 개인 업체)
        if x["허가현황"] and x["허가현황"] not in a["허가현황"]:
            a["허가현황"] += " / " + x["허가현황"]
    결과 = []
    for k in 차례:
        a = 묶음[k]
        a["자료출처"] = " / ".join(sorted(set(a.pop("_출처들"))))
        결과.append(a)
    return 결과


