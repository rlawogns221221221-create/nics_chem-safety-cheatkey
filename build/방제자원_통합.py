# `독성가스` 는 사용자가 2026-09-07 에 더하라고 한 갈래입니다
# ("독성가스는 업체 섭외 항목에 독성가스라는 칸으로 추가 시키도록 하자").
# `폐수 수탁처리` 도 사용자가 **별도 갈래로 두라고 정했습니다**(2026-09-07 —
# "다른갈래로 만들어줘"). 물환경보전법 허가라 폐기물 여섯 갈래에 들어가지
# 않지만 **폐산·알카리 폐수를 받는 곳**이라 화학사고에서 실제로 필요합니다.
# 폐기물 갈래에 억지로 섞지 않습니다 — 허가 근거가 다른 것을 섞으면
# 담당자가 "이 업체가 폐기물도 받는다"고 잘못 읽습니다.


def 업체갈래(업종, 처리방법):
    t = re.sub(r"\s+", "", 업종 or "")
    m = re.sub(r"\s+", "", 처리방법 or "")
    if "중장비" in t:
        return "중장비"
    if "수집" in t or "운반" in t or "수집·운반" in m or "수집운반" in m:
        return "수집·운반"
    if "재활용" in t or m == "재활용":
        return "종합재활용"
    if "최종처분" in t or "최종처리" in t or m == "매립":
        return "최종처분(매립)"
    if "중간처분" in t or "중간처리" in t:
        return "중간처분(소각)" if m == "소각" else "중간처분(그 외)"
    if m == "소각":
        return "중간처분(소각)"
    # 공공폐수처리시설도 폐산·알카리 폐수를 받는 곳이라 화학사고에서
    # 실제로 쓰입니다 — 유니큰과 같은 칸에 둡니다.
    if "폐수" in t:
        return "폐수 수탁처리"
    # 표 03 의 '폐기물 처리업체' 처럼 어느 처분인지 안 적힌 표기.
    # 지어내서 소각·매립으로 정하지 않고 **'중간처분(그 외)'** 로 둡니다
    # (허가현황 칸에 원문이 그대로 남아 있어 무엇인지 보입니다).
    if "폐기물" in t and ("처리" in t or "처분" in t):
        return "중간처분(그 외)"
    return "기타"


