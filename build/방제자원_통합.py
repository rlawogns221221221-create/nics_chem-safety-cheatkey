# 개인정보 검사 — 걸리면 파일을 쓰지 않습니다
# ══════════════════════════════════════════════════════════════
def 개인정보검사(줄들, 이름):
    걸린것 = []
    for i, r in enumerate(줄들):
        for k, v in r.items():
            s = str(v or "")
            if re.search(r"\b01[016789][-\s]?\d{3,4}[-\s]?\d{4}\b", s):
                걸린것.append("%s %d행 %s: %s" % (이름, i + 2, k, s))
    return 걸린것


def 쓰기(파일, 줄들, 열차례):
    os.makedirs(낼폴더, exist_ok=True)
    길 = os.path.join(낼폴더, 파일)
    with open(길, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=열차례, extrasaction="ignore")
        w.writeheader()
        for r in 줄들:
            w.writerow(r)
    print("  %-38s %5d행" % (파일, len(줄들)))
    return 길


