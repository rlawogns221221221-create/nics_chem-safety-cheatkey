def 시군구표만들기():
    """`data/boundaries.js` 에서 (시·군·구 → 시·도) 표를 뽑아 옵니다.

    왜 필요한가 — 표 03 의 주소는 **"여수시 연등1길 175"** 처럼 시·도가
    빠져 있습니다. 시·도를 모르면 권역을 못 정하고, 분류안이 요구한
    '권역 5개 + 시·도' 구분이 그 줄에서 비어 버립니다.
    지어내지 않고 **저장소에 이미 있는 공식 행정경계 자료**(통계청
    센서스용 행정구역경계 · 250개)에서 짝을 읽어 씁니다.

    ⚠ '중구·서구·동구·북구·남구' 처럼 여러 시·도에 같은 이름이 있는 것은
      **일부러 버립니다** — 어느 쪽인지 알 수 없는데 하나로 정하면
      엉뚱한 권역으로 넣게 됩니다.
    """
    길 = os.path.join(뿌리, "data", "boundaries.js")
    if not os.path.exists(길):
        return {}
    with open(길, encoding="utf-8") as f:
        본문 = f.read()
    묶음 = {}
    for 시, 군 in re.findall(r'"s":\s*"([^"]+)",\s*"n":\s*"([^"]+)"', 본문):
        묶음.setdefault(군, set()).add(시도바로잡기.get(시, 시))
    return {k: list(v)[0] for k, v in 묶음.items() if len(v) == 1}


시군구시도 = 시군구표만들기()


def 시도찾기(시도, 주소):
    """시·도 칸이 있으면 그것을, 없으면 주소에서 알아냅니다."""
    s = (시도 or "").strip()
    if s:
        s = 시도바로잡기.get(s, s)
        if s in 시도권역:
            return s
    a = re.sub(r"\s+", " ", (주소 or "").strip())
    if not a:
        return ""
    # ① 주소가 시·도로 시작하는가 ("경기 화성시 …")
    for 표준, 별칭들 in 시도별칭:
        for 별 in 별칭들:
            if a.startswith(별):
                return 시도바로잡기.get(표준, 표준)
    # ② 시·도가 빠진 주소 — 앞머리의 시·군·구 이름으로 되짚습니다
    m = re.match(r"([가-힣]+(?:시|군|구))", a)
    if m and m.group(1) in 시군구시도:
        return 시군구시도[m.group(1)]
    for 군, 시 in 시군구시도.items():
        if 군 in a:
            return 시
    return ""


