def 물품표준(이름):
    """원래 이름 → (표준명, 분류). 못 맞추면 원래 이름을 그대로 씁니다."""
    n = unicodedata.normalize("NFKC", (이름 or "")).lower()
    n = re.sub(r"\s+", "", n)
    for 표준, 분류, 키워드들 in 물품사전:
        for k in 키워드들:
            if k in n:
                return 표준, 분류
    return (이름 or "").strip(), "기타"


def 개수읽기(값):
    """'458' · '1,234' · '3대' → 숫자. '-' · 빈칸 → None(모름)."""
    s = re.sub(r"[,\s]", "", str(값 or ""))
    if not s or s in ("-", "–", "—", "0"):
        return None if s != "0" else 0
    m = re.search(r"\d+", s)
    return int(m.group(0)) if m else None


def 전화정리(값):
    """번호 여러 개면 첫 번째만. 개인 휴대전화(01x)는 버립니다."""
    s = re.sub(r"\s+", " ", str(값 or "").strip())
    if not s or s in ("-", "없음"):
        return ""
    번호들 = re.findall(r"0\d{1,2}[-\s]?\d{3,4}[-\s]?\d{4}", s)
    for b in 번호들:
        정 = re.sub(r"\s", "-", b)
        if not re.match(r"^01", 정):
            return 정
    return ""


def 읽기(파일):
    길 = os.path.join(표폴더, 파일)
    if not os.path.exists(길):
        return []
    with open(길, encoding="utf-8-sig") as f:
        return list(csv.DictReader(f))


def 열(행, *이름들):
    for n in 이름들:
        if n in 행 and (행[n] or "").strip():
            return (행[n] or "").strip()
    return ""


