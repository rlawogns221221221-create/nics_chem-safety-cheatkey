def 찾을권역만들기(소재권역, 협의권역):
    """**소재 권역 + 협의 권역**을 합칩니다 — 화면의 권역 고르기가 쓰는 값.

    왜 합치나 — 업체가 있는 곳과 **맡기로 한 곳이 다릅니다.**
      · (주)세송유화텍은 충북 진천에 있는데 **강원권**을 맡습니다
        ("강원권에 업체가 없어서 가까운 충북을 넣은 것" · 2026-09-07 사용자).
      · 씨이케이는 여수에 있는데 **경상권**도 맡습니다.
      · (주)상록은 여수에 있는데 **충청권**도 맡습니다.
    소재 권역만 쓰면 강원권 담당자가 세송유화텍을 못 찾고, 협의 권역만
    쓰면 충북 담당자가 못 찾습니다. **둘 다에서 찾히게** 합니다
    (2026-09-07 사용자 지시 — "둘다 넣어줘").
    """
    낸다 = []
    # ⚠ **두 인자 모두 쪼갭니다.** 합칠 때 이 함수에 이미 "·" 로 이어 붙인
    #   값이 다시 들어옵니다 — 첫 인자를 통째로 하나로 보면 같은 권역이
    #   여러 번 붙습니다("전라권역·충청권역·전라권역").
    for 묶음 in (소재권역, 협의권역):
        for v in re.split(r"[·,/]", 묶음 or ""):
            v = 협의권역이름.get((v or "").strip(), (v or "").strip())
            if v and v not in 낸다:
                낸다.append(v)
    # 권역 차례대로 늘어놓습니다 — 화면에서 순서가 흔들리지 않게
    차례 = [k for k, _ in 권역표]
    낸다.sort(key=lambda v: 차례.index(v) if v in 차례 else 99)
    return "·".join(낸다)


def 시군구찾기(시군구, 주소, 시도):
    """시·군·구 칸이 없으면 주소에서 두 번째 토막을 씁니다."""
    g = (시군구 or "").strip()
    if g and g != 시도:
        return g
    a = re.sub(r"\s+", " ", (주소 or "").strip())
    for 표준, 별칭들 in 시도별칭:
        for 별 in sorted(별칭들, key=len, reverse=True):
            if a.startswith(별):
                남 = a[len(별):].strip()
                m = re.match(r"([가-힣]+(?:시|군|구))", 남)
                return m.group(1) if m else ""
    return ""


