def 표시표(머리글들, 항목들):
    """[√][항목][한 줄 적기] — 겪은 것에 √ 하고 그 자리에서 한 줄을 적습니다.
       표시만 받고 끝내면 "무엇이" 불편했는지가 남지 않습니다."""
    폭들 = [2600, 21000]
    폭들.append(표폭 - sum(폭들))
    행들 = [[{"글들": [h], "charPr": 머리, "paraPr": 가운데, "크기": 1000,
              "테두리": 머리칸} for h in 머리글들]]
    for t in 항목들:
        행들.append([
            {"글들": [""], "charPr": 글, "paraPr": 가운데, "크기": 1000, "테두리": 속칸},
            {"글들": [t], "charPr": 글, "paraPr": 왼쪽, "크기": 1000, "테두리": 속칸},
            {"글들": [""], "charPr": 글, "paraPr": 왼쪽, "크기": 1000, "테두리": 속칸},
        ])
    return 표(행들, 폭들)[0]


