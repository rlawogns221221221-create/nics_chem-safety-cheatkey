# ══ hwpx 를 다루는 최소한의 도구 ═════════════════════════════════
def 이스케이프(t):
    return (t.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


def 덩어리들(s, tag):
    """최상위 <tag> 덩어리들의 (시작, 끝).

       두 가지를 함께 다뤄야 합니다.
       · 같은 이름이 안에 또 있는 경우(표 안의 문단) — 깊이를 세어 짝을 맞춥니다.
       · **스스로 닫는 태그**(`<hp:run charPrIDRef="37"/>` — 빈 칸이 그렇습니다)
         — 닫는 태그가 없으므로 그 자리에서 끝납니다. 이것을 빠뜨리면 뒤의
         엉뚱한 `</hp:run>` 까지 한 덩어리로 잡습니다."""
    out = []
    열기 = re.compile(r"<" + tag + r"(?=[\s/>])")
    닫기 = "</%s>" % tag

    def 혼자닫나(pos):
        끝 = s.find(">", pos)
        return (끝 != -1 and s[끝 - 1] == "/"), 끝

    i = 0
    while True:
        m = 열기.search(s, i)
        if not m:
            return out
        st = m.start()
        혼자, 태그끝 = 혼자닫나(st)
        if 태그끝 == -1:
            raise SystemExit("hwpx 구조가 예상과 다릅니다: %s 태그가 안 닫힙니다" % tag)
        if 혼자:
            out.append((st, 태그끝 + 1))
            i = 태그끝 + 1
            continue
        깊이 = 0
        j = 태그끝
        while True:
            mo = 열기.search(s, j + 1)
            mc = s.find(닫기, j + 1)
            if mc == -1:
                raise SystemExit("hwpx 구조가 예상과 다릅니다: %s 짝이 없습니다" % tag)
            if mo and mo.start() < mc:
                안혼자, 안끝 = 혼자닫나(mo.start())
                if 안혼자:                      # 안쪽의 스스로 닫는 태그는 세지 않습니다
                    j = 안끝
                else:
                    깊이 += 1
                    j = mo.start()
            else:
                if 깊이 == 0:
                    en = mc + len(닫기)
                    break
                깊이 -= 1
                j = mc
        out.append((st, en))
        i = en


def 글자(블록):
    return "".join(re.findall(r"<hp:t>(.*?)</hp:t>", 블록, re.S))


def 글바꾸기(문단, 새글):
    """문단의 글자를 바꿉니다. 글자 모양(charPrIDRef)은 원래 것을 그대로 씁니다."""
    m = re.search(r"<hp:run\b[^>]*charPrIDRef=\"(\d+)\"", 문단)
    if not m:
        raise SystemExit("문단에 run 이 없습니다: %r" % 글자(문단)[:40])
    새run = '<hp:run charPrIDRef="%s"><hp:t>%s</hp:t></hp:run>' % (
        m.group(1), 이스케이프(새글))
    자리 = 덩어리들(문단, "hp:run")            # 스스로 닫는 run 도 함께 옵니다
    if not 자리:
        raise SystemExit("run 자리를 못 찾았습니다")
    out = 문단[:자리[0][0]] + 새run
    끝 = 자리[0][1]
    for a, b in 자리[1:]:                      # 뒤에 붙은 run 은 지웁니다
        out += 문단[끝:a]
        끝 = b
    out += 문단[끝:]
    # ⚠ 줄배치 캐시는 **첫 줄만 남깁니다.**
    #   전부 남기면 글이 길어져도 한글이 옛 줄 수로 그리고, 통째로 지우면
    #   문단에 그 요소가 아예 없어져 규격을 벗어날 수 있습니다. 첫 줄
    #   하나만 두면 "여기서부터 시작" 만 알려 주고 나머지는 한글이 다시 잽니다.
    def 첫줄만(m):
        줄 = re.search(r"<hp:lineseg\b[^>]*/>", m.group(0))
        return "<hp:linesegarray>%s</hp:linesegarray>" % (줄.group(0) if 줄 else "")
    out = re.sub(r"<hp:linesegarray>.*?</hp:linesegarray>", 첫줄만, out, flags=re.S)
    return out


def 복제(문단, 새글):
    """같은 모양의 문단을 하나 더 만듭니다(id 는 겹치지 않게 0 으로)."""
    새 = 글바꾸기(문단, 새글)
    return re.sub(r'(<hp:p\b[^>]*?)\sid="\d+"', r'\1 id="0"', 새, count=1)


def 표채우기(표, 행들):
    """머리글 아래 자료 행을 채웁니다. 모자라면 자료 행을 복제하고 남으면 지웁니다.
       cellAddr 의 rowAddr 과 표의 rowCnt 를 함께 고쳐야 한글이 표를 제대로 엽니다."""
    tr = 덩어리들(표, "hp:tr")
    if len(tr) < 2:
        raise SystemExit("표에 자료 행이 없습니다")
    머리 = 표[tr[0][0]:tr[0][1]]
    본 = 표[tr[1][0]:tr[1][1]]
    앞 = 표[:tr[0][0]]
    뒤 = 표[tr[-1][1]:]

    새행들 = []
    for r, 줄 in enumerate(행들, start=1):
        행 = 본
        tc = 덩어리들(행, "hp:tc")
        if len(tc) != len(줄):
            raise SystemExit("표의 칸 수(%d)와 자료 칸 수(%d)가 다릅니다" % (len(tc), len(줄)))
        조각 = []
        끝 = 0
        for (a, b), 값 in zip(tc, 줄):
            칸 = 행[a:b]
            문단 = 덩어리들(칸, "hp:p")[0]
            칸 = 칸[:문단[0]] + 글바꾸기(칸[문단[0]:문단[1]], 값) + 칸[문단[1]:]
            칸 = re.sub(r'(<hp:cellAddr colAddr="\d+" rowAddr=")\d+(")',
                        r"\g<1>%d\g<2>" % r, 칸)
            조각.append(행[끝:a] + 칸)
            끝 = b
        조각.append(행[끝:])
        새행들.append("".join(조각))

    새표 = 앞 + 머리 + "".join(새행들) + 뒤
    새표 = re.sub(r'(<hp:tbl\b[^>]*?)rowCnt="\d+"',
                  r'\g<1>rowCnt="%d"' % (len(행들) + 1), 새표, count=1)
    return 새표


