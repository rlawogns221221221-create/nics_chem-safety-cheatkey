def 만들기():
    if not 양식파일.exists():
        raise SystemExit("양식이 없습니다: %s" % 양식파일)

    with zipfile.ZipFile(양식파일) as z:
        속 = {n: z.read(n) for n in z.namelist()}
    s = 속["Contents/section0.xml"].decode("utf-8")

    문단들 = 덩어리들(s, "hp:p")
    남은 = {k: list(v) for k, v in 내용.items()}
    쓴횟수 = {}
    조각 = []
    끝 = 0
    바뀐 = 0

    for a, b in 문단들:
        블록 = s[a:b]
