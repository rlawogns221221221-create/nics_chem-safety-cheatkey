def 칸채우기(칸, 줄들):
    """칸(<hp:tc>…</hp:tc>)의 문단들을 우리 문단으로 바꿉니다. 첫 문단에서 폭·시작 높이·스타일을 읽습니다."""
    a = 칸.index("<hp:subList")
    a = 칸.index(">", a) + 1
    b = 칸.index("</hp:subList>")
    첫 = re.search(r'<hp:p\b[^>]*styleIDRef="(\d+)"', 칸[a:b])
    seg = re.search(r'<hp:lineseg\b[^>]*vertpos="(-?\d+)"[^>]*horzsize="(\d+)"', 칸[a:b])
    스타일, 세로, 폭 = 첫.group(1), int(seg.group(1)), int(seg.group(2))
    조각 = []
    for 꼴, 글 in 줄들:
        xml, n = 문단만들기(꼴, 글, 폭, 세로, 스타일)
        조각.append(xml)
        세로 += n * (줄높이 + 줄간격) + 문단사이
    return 칸[:a] + "".join(조각) + 칸[b:]


