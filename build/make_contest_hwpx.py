def 흰그림(w, h):
    """흰 PNG — 표준 라이브러리만(이 자리의 PIL 이 깨져 있어 쓰지 않습니다)."""
    import struct
    import zlib

    def 덩이(종류, 몸):
        return (struct.pack(">I", len(몸)) + 종류 + 몸
                + struct.pack(">I", zlib.crc32(종류 + 몸) & 0xFFFFFFFF))
    줄 = b"\x00" + b"\xff" * (w * 3)
    return (b"\x89PNG\r\n\x1a\n" + 덩이(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
            + 덩이(b"IDAT", zlib.compress(줄 * h)) + 덩이(b"IEND", b""))


