# ── 기계 부분 ─────────────────────────────────────────────────

def 감싸기(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def 풀기(s):
    return s.replace("&amp;", "&").replace("&lt;", "<").replace("&gt;", ">")


# ⚠ `<hp:t` 로 시작하는 태그가 글칸만 있는 것이 아닙니다 — `<hp:tc`(표 칸)·
# `<hp:tbl`(표) 도 같은 다섯 글자로 시작합니다. `[^>]*>` 로 이어 붙이면 표 칸
# 태그를 글칸으로 착각해, 짝이 되는 `</hp:t>` 를 한참 뒤에서 찾아 그 사이의
# 표 구조를 통째로 삼켜 버립니다(실제로 두 번 깨뜨렸습니다).
# 그래서 `<hp:t>` 또는 `<hp:t 속성…>` 처럼 **바로 닫히거나 공백이 오는 것만**
# 잡습니다. 혼자 닫는 `<hp:t/>`(빈 글칸)는 아래 handler 에서 걸러 냅니다.
글조각 = re.compile(r"(<hp:t(?:\s[^>]*)?>)(.*?)(</hp:t>)", re.S)


def 글바꾸기(xml, 규칙들):
    """<hp:t> 안의 글만 바꿉니다. 태그·속성은 건드리지 않습니다."""
    센것 = []
    for 조각, 방식, 새글 in 규칙들:
        찾음 = [0]

        def 한칸(m, 조각=조각, 방식=방식, 새글=새글, 찾음=찾음):
            if m.group(1).endswith("/>"):      # 혼자 닫는 빈 글칸
                return m.group(0)
            글 = 풀기(m.group(2))
            if 조각 not in 글:
                return m.group(0)
            찾음[0] += 1
            if 방식 == "sub":
                새 = 글.replace(조각, 새글)
            elif 방식 == "del":
                새 = ""
            else:                      # run — 그 칸의 글 전체를 갈아 끼웁니다
                if 찾음[0] > 1:        # 'run' 은 한 군데만 — 두 번째는 그대로
                    찾음[0] -= 1
                    return m.group(0)
                새 = 새글
            return m.group(1) + 감싸기(새) + m.group(3)

        xml = 글조각.sub(한칸, xml)
        센것.append((조각, 찾음[0]))
    return xml, 센것


def 문단자리(xml):
    """겹치는 문단(표를 품은 문단)까지 바르게 잡아 [(시작, 끝)] 로 돌려줍니다.

    ⚠ 정규식 하나로 `<hp:p …>…</hp:p>` 를 잡으면 표(hp:tbl) 안 문단과 짝이
    엉켜 XML 이 깨집니다 — 여는·닫는 태그를 세어 짝을 맞춥니다
    (`공유대회_서식.py` 와 같은 이유·같은 방법).
    """
    tok = re.compile(r"<hp:p\b[^>]*?(/?)>|</hp:p>")
    스택, 결과 = [], []
    for m in tok.finditer(xml):
        if m.group(0).startswith("</"):
            결과.append((스택.pop(), m.end()))
        elif m.group(1) == "/":
            결과.append((m.start(), m.end()))
        else:
            스택.append(m.start())
    if 스택:
        raise SystemExit("문단 태그의 짝이 맞지 않습니다")
    return sorted(결과)


def 복제해서끼우기(xml, 앵커, 새글, 몇번째=1):
    """앵커가 든 문단을 복제해 바로 뒤에 한 줄 끼웁니다.

    복제하므로 문단모양(paraPrIDRef)·글자모양(charPrIDRef)이 원본과 같습니다 —
    우리가 글꼴 이름을 적을 필요가 없습니다.
    """
    본 = 0
    for m in 글조각.finditer(xml):
        if m.group(1).endswith("/>"):
            continue
        if 앵커 in 풀기(m.group(2)):
            본 += 1
            if 본 == 몇번째:
                자리 = m.start()
                break
    else:
        raise SystemExit("끼울 자리를 못 찾았습니다: %s (%d번째)" % (앵커, 몇번째))

    # 그 자리를 품은 문단 중 **가장 안쪽**(가장 짧은) 것을 고릅니다
    후보 = [(b - a, a, b) for a, b in 문단자리(xml) if a <= 자리 < b]
    if not 후보:
        raise SystemExit("문단을 못 찾았습니다: %s" % 앵커)
    _, 첫, 끝 = min(후보)
    틀 = xml[첫:끝]

    머리 = re.match(r"<hp:p\b[^>]*>", 틀).group(0)
    charPr = re.search(r'charPrIDRef="([^"]+)"', 틀)
    charPr = charPr.group(1) if charPr else "0"
    꼬리 = re.search(r"<hp:linesegarray>.*?</hp:linesegarray>", 틀, re.S)
    꼬리 = 꼬리.group(0) if 꼬리 else ""
    새문단 = ('%s<hp:run charPrIDRef="%s"><hp:t>%s</hp:t></hp:run>%s</hp:p>'
              % (머리, charPr, 감싸기(새글), 꼬리))
    return xml[:끝] + 새문단 + xml[끝:]


def 만들기(원본, 나올곳):
    with zipfile.ZipFile(원본) as z:
        이름들 = z.namelist()
        속 = {n: z.read(n) for n in 이름들}

    xml = 속["Contents/section0.xml"].decode("utf-8")
    xml, 센것 = 글바꾸기(xml, 바꿀것)

    못찾음 = [조각 for 조각, n in 센것 if n == 0]
    if 못찾음:
        raise SystemExit("원본에서 못 찾은 글이 있습니다:\n  - "
                         + "\n  - ".join(못찾음))

    for 앵커, 새글, 몇번째 in 끼울것:
        xml = 복제해서끼우기(xml, 앵커, 새글, 몇번째)

    속["Contents/section0.xml"] = xml.encode("utf-8")

    # 미리보기 글은 새 제목으로 — 옛 제목이 남으면 탐색기에서 헷갈립니다
    if "Preview/PrvText.txt" in 속:
        속["Preview/PrvText.txt"] = (새제목 + "\n화학물질안전원").encode("utf-8")

    # mimetype 은 압축하지 않고 맨 앞에 두는 것이 규칙입니다
    with zipfile.ZipFile(나올곳, "w", zipfile.ZIP_DEFLATED) as z:
        if "mimetype" in 속:
            z.writestr(zipfile.ZipInfo("mimetype"), 속["mimetype"],
                       compress_type=zipfile.ZIP_STORED)
        for n in 이름들:
            if n != "mimetype":
                z.writestr(n, 속[n])
    return 나올곳


