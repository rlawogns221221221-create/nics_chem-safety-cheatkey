# ══ 한 줄 CSV 되돌리기 ═══════════════════════════════════════════
def 토큰(s):
    return next(csv.reader(io.StringIO(s)))


def 행으로(본문, 칸수, 첫칸=None):
    """표에서 온 자료는 모든 행의 칸 수가 같다 — 그 점을 이용해 되돌린다.

       K번째 칸은 "이 행의 마지막 칸 + 공백 + 다음 행의 첫 칸"이므로
       뒤에서부터 잘라 본다. 첫 칸의 모양(보통 일련번호)을 알면 더 안전하다."""
    t = 토큰(본문)
    행, 현재 = [], []
    for tok in t:
        if len(현재) == 칸수 - 1:
            if ' ' in tok:
                왼, 오 = 자르기(tok, 첫칸)
                현재.append(왼)
                행.append(현재)
                현재 = [오]
            else:
                현재.append(tok)
                행.append(현재)
                현재 = []
        else:
            현재.append(tok)
    if 현재:
        행.append(현재 + [''] * (칸수 - len(현재)))
    return 행


def 자르기(tok, 첫칸):
    if 첫칸:
        for m in reversed(list(re.finditer(' ', tok))):
            오 = tok[m.end():]
            if re.fullmatch(첫칸, 오):
                return tok[:m.start()], 오
    p = tok.rfind(' ')
    return tok[:p], tok[p + 1:]


