# 원자료에는 가운뎃점 자리에 **엉뚱한 문자**가 섞여 있습니다 —
# `수집〮운반업` 의 〮 는 U+302E(한글 방점)이고, `수집∙운반업체` 의 ∙ 는
# U+2219(수학 기호)입니다. 눈으로는 구분이 안 되는데 **검색이 안 걸립니다**
# ("수집운반"으로 찾으면 566건 중 1건만 나왔습니다). 전부 · 로 맞춥니다.
가운뎃점 = {'\u302e': '·', '\u2219': '·', '\u2022': '·', '\u2027': '·',
          '\u30fb': '·', '\ufeff': ''}


def 글자다듬기(v):
    if not isinstance(v, str):
        return v
    for a, b in 가운뎃점.items():
        v = v.replace(a, b)
    return v


